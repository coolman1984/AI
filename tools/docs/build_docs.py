"""Generate the reference part of the documentation from the code, so it is never out of date.

    python tools/docs/build_docs.py           write the files
    python tools/docs/build_docs.py --check   exit 1 if a generated file differs (used by check_all)

Generated (do not edit by hand):
  docs/SCREENS.md      every menu area, group and screen (T-code) with its title
  docs/API.md          every JSON route of the server with its authorization area
  docs/ERROR_CODES.md  every business message (class + number) raised by the engines
  docs/TESTS.md        the process test catalog: test cases and the unit tests behind them
  docs/CHANGELOG.md    merged pull requests from the git history (written, not checked)
Standard library only.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
HEAD = "<!-- Generated by tools/docs/build_docs.py - do not edit by hand. -->\n\n"


def read(*p):
    with open(os.path.join(ROOT, *p), encoding="utf-8") as f:
        return f.read()


def _js_array(text):
    """a JS array literal of strings / arrays (as in menu.js) -> Python list"""
    text = re.sub(r"^\s*//.*$", "", text, flags=re.M)
    text = re.sub(r",(\s*[\]\)])", r"\1", text)
    return json.loads(text)


def menu():
    js = read("web", "static", "menu.js")
    a = js.index("const MENU = [") + len("const MENU = ")
    b = js.index("\n];", a) + 2
    tree = _js_array(js[a:b])
    if "MENU.push(" in js:
        p = js.index("MENU.push(") + len("MENU.push(")
        q = js.index("]]);", p) + 2
        tree += _js_array("[" + js[p:q] + "]")
    m = re.search(r"const TOP = (\[.*?\]);", js, re.S)
    top = _js_array(m.group(1)) if m else []
    tree.sort(key=lambda x: top.index(x[0]) if x[0] in top else 99)
    return tree


def screens_md():
    titles = json.loads(read("web", "static", "tcodes.json"))
    tree = menu()
    seen, out = set(), [HEAD, "# Screens (T-codes)\n\n",
                        "Type the code in the top field of NERP. %d screens, by menu area.\n\n" % len(titles)]
    out.append("Areas: " + " · ".join("[%s](#%s)" % (t, re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")) for t, _ in tree) + "\n\n")

    def walk(node, depth):
        name, kids = node
        out.append("%s %s\n\n" % ("#" * min(depth + 2, 4), name))
        rows = [k for k in kids if isinstance(k, str)]
        if rows:
            out.append("| Code | Screen |\n|---|---|\n")
            for c in rows:
                c = c.lstrip("!")
                seen.add(c)
                out.append("| `%s` | %s |\n" % (c, titles.get(c, "").replace("|", "/")))
            out.append("\n")
        for k in kids:
            if not isinstance(k, str):
                walk(k, depth + 1)
    for area in tree:
        walk(area, 0)
    rest = sorted(c for c in titles if c not in seen)
    if rest:
        out.append("## Other screens (opened from other screens or by code)\n\n| Code | Screen |\n|---|---|\n")
        out += ["| `%s` | %s |\n" % (c, titles[c].replace("|", "/")) for c in rest]
    return "".join(out)


def api_md():
    from sec.config import API_AREAS
    routes = []
    for f in sorted(os.listdir(os.path.join(ROOT, "web"))):
        if not f.endswith(".py"):
            continue
        src = read("web", f)
        for m in re.finditer(r'@route\("(\w+)",\s*"([^"]+)"\)\s*\ndef (\w+)\([^)]*\):\s*(?:"""(.*?)""")?', src, re.S):
            method, pat, fn, doc = m.groups()
            path = re.sub(r"\(\?P<(\w+)>[^)]*\)", r"<\1>", pat).replace("\\", "")
            area = next((a for p, a in API_AREAS if path.startswith(p)), "")
            routes.append((path, method, f, fn, " ".join((doc or "").split())[:140]))
    routes.sort()
    out = [HEAD, "# JSON API\n\n", "%d routes. Area = authorization area checked by the server (`sec/config.py` API_AREAS); "
           "GET needs display (03), POST needs change (02).\n\n" % len(routes),
           "| Method | Path | Area | File · function | Purpose |\n|---|---|---|---|---|\n"]
    out += ["| %s | `%s` | %s | `%s` · `%s` | %s |\n" % (m, p.replace("|", "\\|"), a or "-", f, fn, d.replace("|", "/"))
            for p, m, f, fn, d in [(r[0], r[1], r[2], r[3], r[4]) for r in routes]
            for a in [next((x for pp, x in API_AREAS if p.startswith(pp)), "")]]
    return "".join(out)


ERR = re.compile(r'MMError\(\s*(?P<msg>(?:[rf]?"(?:[^"\\]|\\.)*"\s*)+)(?P<rest>.*?),\s*"(?P<cls>[A-Z0-9]{2})",\s*"(?P<no>\d{3})"\s*\)', re.S)


def errors_md():
    files = subprocess.run(["git", "ls-files", "*.py"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    found = {}
    for f in files:
        if f.startswith(("tests/", "tools/")):
            continue
        for m in ERR.finditer(read(f)):
            msg = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group("msg")))
            msg = re.sub(r"%[-0-9.]*[sdfr]", "…", msg).replace("|", "/")
            found.setdefault((m.group("cls"), m.group("no")), []).append((msg, f))
    out = [HEAD, "# Business messages (error codes)\n\n",
           "Message class + number as shown in the status bar (e.g. `AU 906`). %d codes. `…` = a value filled in at run time.\n\n" % len(found),
           "| Class | No. | Message | Where |\n|---|---|---|---|\n"]
    for (cls, no), lst in sorted(found.items()):
        msgs = list(dict.fromkeys(x[0] for x in lst))
        where = ", ".join(sorted(set("`%s`" % x[1] for x in lst)))
        out.append("| %s | %s | %s | %s |\n" % (cls, no, " / ".join(msgs)[:300], where))
    return "".join(out)


def tests_md():
    from qa import catalog
    out = [HEAD, "# Process test catalog\n\n",
           "Every business process has test cases; each case is proven by unit tests (run by `python tools/qa/check_all.py` "
           "and screen ZQA_TEST).\n\n"]
    total = 0
    for p in catalog.PROCESSES:
        tests = p.get("cases") or []
        total += len(tests)
        out.append("## %s - %s\n\n%s\n\n| Case | Test | Screens | Expected result | Unit tests |\n|---|---|---|---|---|\n"
                   % (p["id"], p["name"], p.get("purpose", "")))
        for t in tests:
            tid, title, codes, expected, units = t[:5]
            out.append("| %s | %s | %s | %s | %s |\n" % (tid, title, codes, expected.replace("|", "/"),
                                                      "<br>".join("`%s`" % u for u in units)))
        out.append("\n")
    out.insert(2, "%d processes, %d test cases.\n\n" % (len(catalog.PROCESSES), total))
    return "".join(out)


def changelog_md():
    log = subprocess.run(["git", "log", "--first-parent", "--merges", "--date=short", "--pretty=format:%ad\t%s\t%b%x00"],
                         cwd=ROOT, capture_output=True, text=True).stdout
    rows = []
    for rec in log.split("\x00"):
        rec = rec.strip()
        if not rec:
            continue
        parts = rec.split("\t", 2)
        if len(parts) < 3:
            continue
        date, subj, body = parts
        m = re.search(r"#(\d+)", subj)
        title = body.strip().splitlines()[0] if body.strip() else subj
        if m:
            rows.append((int(m.group(1)), date, title))
    out = [HEAD, "# Change log\n\n", "Every merged pull request, newest first (from the git history). "
           "Details: the pull request on GitHub and `docs/KNOWLEDGE.md`.\n\n", "| PR | Date | Change |\n|---|---|---|\n"]
    out += ["| [#%d](https://github.com/coolman1984/AI/pull/%d) | %s | %s |\n" % (n, n, d, t.replace("|", "/")) for n, d, t in rows]
    return "".join(out)


CHECKED = {"SCREENS.md": screens_md, "API.md": api_md, "ERROR_CODES.md": errors_md, "TESTS.md": tests_md}


def main():
    check = "--check" in sys.argv
    stale = []
    for name, fn in CHECKED.items():
        text = fn()
        path = os.path.join(ROOT, "docs", name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if check:
            if old != text:
                stale.append(name)
        elif old != text:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("written docs/%s" % name)
    if check:
        print("generated docs up to date" if not stale else
              "out of date: %s - run: python tools/docs/build_docs.py" % ", ".join("docs/" + s for s in stale))
        sys.exit(1 if stale else 0)
    with open(os.path.join(ROOT, "docs", "CHANGELOG.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(changelog_md())
    print("written docs/CHANGELOG.md")


if __name__ == "__main__":
    main()
